const FALLBACK = 'zh';
let current = FALLBACK;

function isSupported(lang) {
  return Object.prototype.hasOwnProperty.call(DICT, lang);
}

function setLanguage(lang) {
  current = isSupported(lang) ? lang : FALLBACK;
  return current;
}

function getLanguage() { return current; }

// Missing keys fall back to Chinese and then to the key itself, so a typo shows
// up as a visible key instead of an empty button.
function t(key, vars) {
  const text = DICT[current]?.[key] ?? DICT[FALLBACK][key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

const api = { LANGUAGES, DICT, t, setLanguage, getLanguage, isSupported };

if (typeof module === 'object' && module.exports) module.exports = api;
else root.novaI18n = api;

